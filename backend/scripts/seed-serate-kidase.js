async function main() {
  await mongoose.connect(process.env.MONGODB_URI, {
    dbName: 'church_db', family: 4, retryWrites: false,
  });
  console.log('Connected');

  let book = await LiturgicalBook.findOne({ titleGez: 'ሥርዓተ ቅዳሴ' });
  if (!book) {
    book = await LiturgicalBook.create({
      title:          'Preparatory Service (Sirate Kidase)',
      titleGez:       'ሥርዓተ ቅዳሴ',
      titleAmh:       'ሥርዓተ ቅዳሴ',
      description:    'The preparatory service performed before the Divine Liturgy. Contains all prayers, priest-deacon-people dialogues, and anaphora preparation rites. Trilingual: Ge\'ez, Amharic, English.',
      type:           'liturgy',
      tradition:      'ethiopian-orthodox',
      languages:      ['gez', 'amh', 'en'],
      status:         'published',
      featured:       false,
      tags:           ['liturgy', 'preparatory', 'kidase', 'serate'],
      searchKeywords: ['serate kidase','preparatory','ሥርዓተ ቅዳሴ'],
    });
    console.log('Created book:', book._id.toString(), book.titleGez);
  } else {
    console.log('Found book:', book._id.toString(), book.titleGez);
  }

  const BOOK_ID = book._id.toString();

  // Clear old blocks in batches
  const existingIds = await LiturgicalBlock.find({ bookId: BOOK_ID }).select('_id');
  console.log('Clearing', existingIds.length, 'existing blocks...');
  for (let i = 0; i < existingIds.length; i += BATCH) {
    const ids = existingIds.slice(i, i + BATCH).map(d => d._id);
    await LiturgicalBlock.deleteMany({ _id: { $in: ids } });
    await new Promise(r => setTimeout(r, DELAY));
  }

  // Build blocks
  const blocks = SECTIONS.map((s, idx) => {
    const blockId = 'serate-kidase-' + String(s.no).replace(/\s+/g, '-') + '-' + (idx + 1);
    return {
      blockId,
      bookId:      BOOK_ID,
      sectionId:   'sirate-kidase',
      subtitle:    String(s.no),
      order:       idx + 1,
      globalOrder: idx + 1,
      role:        s.role || 'priest',
      type:        s.role === 'rubric' ? 'rubric' :
                   s.role === 'dialogue' ? 'dialogue' :
                   s.role === 'people'  ? 'response' : 'prayer',
      translations: new Map([['gez', s.gez], ['amh', s.amh], ['en', s.en]]),
      isRubric:     s.role === 'rubric',
      isResponsive: s.role === 'dialogue' || s.role === 'people',
    };
  });

  console.log('Inserting', blocks.length, 'blocks...');
  let done = 0;
  for (let i = 0; i < blocks.length; i += BATCH) {
    const batch = blocks.slice(i, i + BATCH);
    await LiturgicalBlock.insertMany(batch);
    done += batch.length;
    process.stdout.write('\r  ' + done + '/' + blocks.length + ' blocks done');
    if (i + BATCH < blocks.length) await new Promise(r => setTimeout(r, DELAY));
  }

  const total = await LiturgicalBlock.countDocuments({ bookId: BOOK_ID });
  await LiturgicalBook.findByIdAndUpdate(BOOK_ID, { blockCount: total, status: 'published' });

  console.log('\n\nDone!  Book:', BOOK_ID, '| Blocks:', total);
  await mongoose.disconnect();
  process.exit(0);
}

main().catch(e => { console.error('\nERR:', e.message); process.exit(1); });
