// ── Main ──────────────────────────────────────────────────────────────────────
async function main() {
  console.log('\n═══════════════════════════════════════════════════════════');
  console.log('  SEED: ግጻዌ (Gtsawie / Daily Lectionary)');
  console.log('═══════════════════════════════════════════════════════════\n');

  await mongoose.connect(process.env.MONGODB_URI, {
    dbName: 'church_db',
    retryWrites: false,
    tls: true,
    family: 4,
    serverSelectionTimeoutMS: 30000,
  });
  console.log('Connected to database\n');

  // ── 1. Find or create the ግጻዌ book ────────────────────────────────────
  // Look for existing book by title to avoid duplicates
  let book = await LiturgicalBook.findOne({
    $or: [
      { titleGez: 'ግጻዌ' },
      { title: { $regex: /gtsawie/i } },
    ]
  });

  if (!book) {
    console.log('Creating LiturgicalBook for ግጻዌ...');
    book = await LiturgicalBook.create({
      title:       'Gtsawie (Daily Lectionary)',
      titleGez:    'ግጻዌ',
      titleTi:     'ግጻዌ',
      description: [
        'Daily liturgical lectionary for the full Eritrean Orthodox year (13 months).',
        'For each day: morning psalm, morning Gospel, Pauline epistle,',
        'Apostles reading, Acts reading, pre-liturgy psalm, liturgy Gospel,',
        'appointed Anaphora, and brief commemoration of saints.',
        '',
        'For full saint biographies, see the linked ስንክሳር (Synaxar) book.',
        'Tradition: Debre Abbay (ደብር ዓባይ).'
      ].join(' '),
      category:    'synaxar',   // closest available category (lectionary)
      type:        'liturgy',
      tradition:   'eritrean-orthodox',
      languages:   ['gez'],     // ti and en to be added by volunteers
      status:      'draft',
      featured:    true,
      blockCount:  0,
      createdBy:   'seed-script',
    });
    console.log(`  ✅ Created book: ${book._id} — ግጻዌ`);
  } else {
    console.log(`  ✅ Found existing book: ${book._id} — "${book.titleGez}"`);
  }

  const BOOK_ID = book._id.toString();

  // ── 2. Build blocks (9 slots per day) ─────────────────────────────────
  const blocks = [];

  for (const day of RAW_DAYS) {
    const monthIdx = MONTHS.indexOf(day.month);
    if (monthIdx === -1) { console.warn(`  ⚠️  Unknown month: ${day.month}`); continue; }

    const gezNum = GEZ_NUMS[day.day - 1];
    if (!gezNum) { console.warn(`  ⚠️  Day out of range: ${day.day}`); continue; }

    for (const [slotStr, text] of Object.entries(day.slots)) {
      const slot    = parseInt(slotStr);
      const slotDef = SLOTS[slot];
      if (!slotDef) continue;

      const blockId = `gtsawie-${day.month}-d${String(day.day).padStart(2,'0')}-s${slot}`;

      blocks.push({
        blockId,
        bookId:    BOOK_ID,
        sectionId: day.month,    // month = section (navigation)
        subtitle:  gezNum,       // day numeral = subtitle (sub-navigation)
        order:     slot,         // slot within the day (1..9)
        type:      slotDef.type,
        role:      slotDef.role,
        translations: { gez: text.trim() },
        isRubric:     false,
        isResponsive: false,
        metadata: {
          enteredBy: 'seed-script',
          language:  'gez',
          notes:     slotDef.label,
        },
      });
    }
  }

  console.log(`Built ${blocks.length} blocks from ${RAW_DAYS.length} days\n`);

  // ── 3. Clear old blocks for this book then upsert in small batches ─────
  const deleted = await mongoose.connection.collection('liturgical_blocks')
    .deleteMany({ bookId: BOOK_ID });
  console.log(`Cleared ${deleted.deletedCount} existing blocks`);
  await new Promise(r => setTimeout(r, 1000));

  const BATCH = 5;
  const DELAY = 800;
  let done = 0;

  for (let i = 0; i < blocks.length; i += BATCH) {
    const batch = blocks.slice(i, i + BATCH);
    const ops   = batch.map(doc => ({
      updateOne: { filter: { blockId: doc.blockId }, update: { $set: doc }, upsert: true }
    }));

    let attempts = 0;
    while (attempts < 3) {
      try {
        await mongoose.connection.collection('liturgical_blocks').bulkWrite(ops, { ordered: false });
        done += batch.length;
        process.stdout.write(`\r  Upserted ${done}/${blocks.length} blocks...`);
        break;
      } catch (err) {
        attempts++;
        const isRL = err.code === 16500 || (err.message || '').includes('16500');
        if (isRL && attempts < 3) {
          const wait = 3000 * attempts;
          process.stdout.write(`\n  ⚠️  Rate limited — waiting ${wait}ms...\n`);
          await new Promise(r => setTimeout(r, wait));
        } else { throw err; }
      }
    }
    if (i + BATCH < blocks.length) await new Promise(r => setTimeout(r, DELAY));
  }
  console.log(`\nUpserted ${done} blocks`);

  // ── 4. Update blockCount ────────────────────────────────────────────────
  const total = await LiturgicalBlock.countDocuments({ bookId: BOOK_ID });
  await LiturgicalBook.findByIdAndUpdate(BOOK_ID, { blockCount: total, status: 'draft' });

  // ── 5. Summary ──────────────────────────────────────────────────────────
  const byMonth = {};
  for (const d of RAW_DAYS) byMonth[d.month] = (byMonth[d.month] || 0) + 1;

  console.log('\n──────────────────────────────────────────────────────────');
  console.log('SUMMARY');
  console.log('──────────────────────────────────────────────────────────');
  for (const [month, days] of Object.entries(byMonth)) {
    const expected = DAYS_PER_MONTH[month] || 30;
    const slots    = Object.keys(SLOTS).length;
    const flag     = days < expected ? ` ⚠️  (${expected - days} days missing)` : ' ✅';
    console.log(`  ${month}: ${days}/${expected} days × ${slots} slots = ${days * slots} blocks${flag}`);
  }
  console.log(`\n  Total blocks in DB: ${total}`);
  console.log(`  Book ID           : ${BOOK_ID}`);
  console.log(`  Status            : draft → publish via admin UI when ready`);
  console.log('\n  MISSING MONTHS: add ጥቅምት through ጰጉሜ to RAW_DAYS.');
  console.log('  SYNAXAR LINK   : slot 1 (ዝካረ) names link to the Synaxar book.');
  console.log('  TIGRINYA/EN    : to be added by volunteers via the library portal.\n');

  await mongoose.disconnect();
  process.exit(0);
}

main().catch(err => {
  console.error('\n❌ Error:', err.message);
  process.exit(1);
});
