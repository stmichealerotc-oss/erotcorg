// ── Main ──────────────────────────────────────────────────────────────────────
async function main() {
  console.log('\n══════════════════════════════════════════════════════');
  console.log('  SEED: ግጻዌ — 1 block per day, all 9 slots in one');
  console.log('══════════════════════════════════════════════════════\n');

  await mongoose.connect(process.env.MONGODB_URI, {
    dbName:'church_db', retryWrites:false, tls:true, family:4,
    serverSelectionTimeoutMS:30000,
  });
  console.log('Connected\n');

  // ── Find or create the book ───────────────────────────────────────────
  let book = await LiturgicalBook.findOne({ titleGez:'ግጻዌ' });

  if (!book) {
    console.log('Creating book ግጻዌ...');
    book = await LiturgicalBook.create({
      title:       'Gtsawie (Daily Lectionary)',
      titleGez:    'ግጻዌ',
      titleTi:     'ግጻዌ',
      description: 'Daily liturgical lectionary for the full Eritrean Orthodox year (13 months). Each day shows: commemoration, morning psalm, morning Gospel, Pauline epistle, Apostles, Acts, pre-liturgy psalm, liturgy Gospel, and the appointed Anaphora. Tradition: Debre Abbay.',
      category:    'synaxar',
      type:        'liturgy',
      tradition:   'eritrean-orthodox',
      languages:   ['gez'],
      status:      'published',
      featured:    true,
      blockCount:  0,
      createdBy:   'seed-script',
    });
    console.log(`  ✅ Created: ${book._id}`);
  } else {
    console.log(`  ✅ Found: ${book._id} — ${book.titleGez}`);
  }

  const BOOK_ID = book._id.toString();

  // ── Build blocks: 1 per day ────────────────────────────────────────────
  const blocks = RAW_DAYS.map(d => buildBlock(BOOK_ID, d.month, d.day, d.slots));
  console.log(`\nBuilt ${blocks.length} blocks (1 per day) from ${RAW_DAYS.length} days`);

  // ── Clear old blocks in small batches ─────────────────────────────────
  let cleared = 0;
  // Fetch old blockIds first so we can delete in batches
  const oldBlocks = await mongoose.connection.collection('liturgical_blocks')
    .find({ bookId: BOOK_ID }, { projection: { _id: 1 } }).toArray();

  console.log(`Found ${oldBlocks.length} old blocks to clear`);

  const DEL_BATCH = 5;
  for (let i = 0; i < oldBlocks.length; i += DEL_BATCH) {
    const ids = oldBlocks.slice(i, i + DEL_BATCH).map(b => b._id);
    for (let attempt = 1; attempt <= 5; attempt++) {
      try {
        await mongoose.connection.collection('liturgical_blocks')
          .deleteMany({ _id: { $in: ids } });
        cleared += ids.length;
        process.stdout.write(`\r  Cleared ${cleared}/${oldBlocks.length} old blocks...`);
        break;
      } catch (e) {
        if ((e.message||'').includes('16500') && attempt < 5) {
          await new Promise(r => setTimeout(r, 3000 * attempt));
        } else throw e;
      }
    }
    await new Promise(r => setTimeout(r, 500));
  }
  if (oldBlocks.length > 0) console.log('');
  await new Promise(r => setTimeout(r, 1000));

  // ── Upsert in batches ──────────────────────────────────────────────────
  const BATCH = 5, DELAY = 800;
  let done = 0;

  for (let i = 0; i < blocks.length; i += BATCH) {
    const batch = blocks.slice(i, i + BATCH);
    const ops   = batch.map(doc => ({
      updateOne: { filter:{blockId:doc.blockId}, update:{$set:doc}, upsert:true }
    }));

    let attempts = 0;
    while (attempts < 3) {
      try {
        await mongoose.connection.collection('liturgical_blocks')
          .bulkWrite(ops, { ordered:false });
        done += batch.length;
        process.stdout.write(`\r  Upserted ${done}/${blocks.length} blocks...`);
        break;
      } catch (e) {
        attempts++;
        if ((e.message||'').includes('16500') && attempts < 3) {
          await new Promise(r => setTimeout(r, 3000 * attempts));
        } else throw e;
      }
    }
    if (i + BATCH < blocks.length) await new Promise(r => setTimeout(r, DELAY));
  }
  console.log(`\nUpserted ${done} blocks`);

  // ── Update blockCount ──────────────────────────────────────────────────
  const total = await LiturgicalBlock.countDocuments({ bookId:BOOK_ID });
  await LiturgicalBook.findByIdAndUpdate(BOOK_ID, { blockCount:total, status:'published' });

  // ── Summary ────────────────────────────────────────────────────────────
  const byMonth = {};
  for (const d of RAW_DAYS) byMonth[d.month] = (byMonth[d.month]||0) + 1;

  console.log('\n──────────────────────────────────────────────────────');
  for (const [m, days] of Object.entries(byMonth)) {
    const expected = DAYS_PER_MONTH[m] || 30;
    const flag = days < expected ? ` ⚠️  ${expected-days} days missing` : ' ✅';
    console.log(`  ${m}: ${days}/${expected} days${flag}`);
  }
  console.log(`\n  Total blocks: ${total} (1 per day)`);
  console.log(`  Book ID     : ${BOOK_ID}`);
  console.log(`  Status      : published`);
  console.log('\n  Add more months by extending RAW_DAYS.\n');

  await mongoose.disconnect();
  process.exit(0);
}

main().catch(e => { console.error('\n❌', e.message); process.exit(1); });
