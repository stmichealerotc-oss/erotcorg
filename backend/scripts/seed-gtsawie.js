// ── Helper: build one block from a day entry ──────────────────────────────────
// slots: { 1: text, 2: text, ..., 9: text }
function buildBlock(bookId, month, day, slots) {
  const gezNum    = GEZ_NUMS[day - 1];
  const monthIdx  = MONTHS.indexOf(month);
  const blockId   = `gtsawie-${month}-d${String(day).padStart(2,'0')}`;

  // Pack all 9 slots into a single structured JSON string stored in gez
  // The reader component will JSON.parse() this to display each slot
  const structured = JSON.stringify({
    commemoration: slots[1] || '',
    misbak_negah:  slots[2] || '',
    gospel_negah:  slots[3] || '',
    pauline:       slots[4] || '',
    apostles:      slots[5] || '',
    acts:          slots[6] || '',
    misbak_qidat:  slots[7] || '',
    gospel_qidat:  slots[8] || '',
    anaphora:      slots[9] || '',
  });

  return {
    blockId,
    bookId,
    sectionId: month,
    subtitle:  gezNum,
    order:     day,           // 1..30 — one block per day
    type:      'reading',
    role:      'daily',
    translations: { gez: structured },
    isRubric:     false,
    isResponsive: false,
    metadata: {
      enteredBy: 'seed-script',
      language:  'gez',
      notes:     `${month} ${gezNum} — full day lectionary`,
    },
  };
}

